def uri(name):
    d = {"#": "", "+": ""}
    for y, row in enumerate(G[name].split("/")):
        x = 0
        while x < 9:
            c = row[x]
            if c == ".": x += 1; continue
            j = x
            while j < 9 and row[j] == c: j += 1
            d[c] += "M%d %dh%dv1h-%dz" % (x, y, j - x, j - x)
            x = j
    svg = "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 9 9' shape-rendering='crispEdges'><path d='" + d["#"] + "'/>" + ("<path opacity='.45' d='" + d["+"] + "'/>" if d["+"] else "") + "</svg>"
    return "url(\"data:image/svg+xml," + svg.replace("<", "%3C").replace(">", "%3E") + "\")"

